package com.dogukan_tufan.shared_expense_tracking_system.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;

// How much one user owes for a given Expense. A set of these (one per active household member
// at the time the Expense was created/edited) is generated by ExpenseService -- see
// ExpenseService.recalculateShares(). Never created or edited directly through its own endpoint.
// Why the indexes: PostgreSQL does not index foreign keys by itself. Shares are looked up by expense
// (edit, delete) and by user (balances, statements), so both columns get an index.
@Entity
@Table(name = "expense_shares", indexes = {
        @Index(name = "idx_expense_shares_expense_id", columnList = "expense_id"),
        @Index(name = "idx_expense_shares_user_id", columnList = "user_id")
})
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class ExpenseShare {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "expense_id", nullable = false)
    private Expense expense;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @Setter
    @Column(name = "owed_amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal owedAmount;

    // Only filled for PERCENT splits (e.g. 33.33 means 33.33%). Null for EQUAL and AMOUNT shares.
    @Column(precision = 5, scale = 2)
    private BigDecimal percent;

    public ExpenseShare(Expense expense, User user, BigDecimal owedAmount) {
        this(expense, user, owedAmount, null);
    }

    public ExpenseShare(Expense expense, User user, BigDecimal owedAmount, BigDecimal percent) {
        this.expense = expense;
        this.user = user;
        this.owedAmount = owedAmount;
        this.percent = percent;
    }
}
